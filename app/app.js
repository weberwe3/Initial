function searchCourse(query, filter) {
  INDEX ||= buildIndex();
  const STOP = new Set(["how", "to", "a", "an", "the", "do", "does", "i", "is", "what", "of", "my", "can", "you", "use", "using", "me", "make", "get", "and", "or", "in", "it", "should", "when", "why", "python"]);
  const all = tok(query);
  const kept = all.filter(w => !STOP.has(w));
  const words = kept.length ? kept : all;
  if (!words.length) return [];
  const phrase = query.trim().toLowerCase();
  const scoreWord = (e, w) => {
    let best = 0;
    const stem = w.length > 3 && w.endsWith("s") ? w.slice(0, -1) : null;
    for (const v of [w, ...(stem ? [stem] : []), ...(ALIASES[w] || []), ...(stem && ALIASES[stem] || [])]) {
      const weight = v === w ? 1 : 0.6;
      if (e.tCount.has(v)) best = Math.max(best, 10 * weight);
      if (e.bCount.has(v)) best = Math.max(best, (3 + Math.min(e.bCount.get(v), 6)) * weight);
      if (w.length >= 3 && best < 4) {
        for (const k of e.tCount.keys()) if (k.startsWith(v)) { best = Math.max(best, 6 * weight); break; }
        if (best < 2) for (const k of e.bCount.keys()) if (k.startsWith(v)) { best = Math.max(best, 2 * weight); break; }
      }
    }
    return best;
  };
  const run = (requireAll) => INDEX
    .filter(e => !filter || filter === "All" || e.kind === filter || (filter === "Lessons" && e.kind === "Lesson") || (filter === "Flashcards" && e.kind === "Flashcard") || (filter === "Exercises" && e.kind === "Exercise") || (filter === "Projects" && e.kind === "Project"))
    .map(e => {
      const scores = words.map(w => scoreWord(e, w));
      if (requireAll && scores.some(s => s === 0)) return null;
      let score = scores.reduce((a, b) => a + b, 0);
      if (!score) return null;
      if (phrase.length > 2 && e.lower.includes(phrase)) score += 12;
      if (e.kind === "Lesson") score += 1.5;
      return { e, score };
    }).filter(Boolean).sort((a, b) => b.score - a.score).slice(0, 40);
  const strict = run(true);
  return strict.length ? strict : run(false).map(r => ({ ...r, loose: true }));
}
