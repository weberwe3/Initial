function interleave(ids) {
  // round-robin across modules so consecutive items come from different topics
  const groups = {};
  shuffle(ids).forEach(id => (groups[id.split("-")[1]] ||= []).push(id));
  const lists = shuffle(Object.values(groups)); const out = [];
  while (lists.some(l => l.length)) lists.forEach(l => l.length && out.push(l.shift()));
  return out;
}

