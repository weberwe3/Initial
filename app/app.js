function render() {
  const route = location.hash.slice(1) || "home";
  liveEditors = [];
  const view = $("#view"); view.innerHTML = "";
  let nodes, crumb;
  if (route.startsWith("m-") && byId[route.slice(2)]) { const m = byId[route.slice(2)]; nodes = viewModule(m.id); crumb = `<b>Module ${m.id}</b> · ${esc(m.title)}`; }
  else if (route === "review") { nodes = viewReview(); crumb = "<b>Review</b>"; }
  else if (route === "play") { nodes = viewPlay(); crumb = "<b>Playground</b>"; }
  else if (route === "notebook") { nodes = viewNotebook(); crumb = "<b>Notebook</b>"; }
  else if (route === "science") { nodes = viewScience(); crumb = "<b>How it's designed</b>"; }
  else if (route === "cheatsheet") { nodes = viewDoc(C.cheatsheet, "Reference"); crumb = "<b>Cheatsheet</b>"; }
  else if (route.startsWith("project-")) { const p = C.projects.find(x => "project-" + x.n === route); nodes = p ? viewDoc(p.md, "Project") : viewHome(); crumb = p ? `<b>${esc(p.title)}</b>` : ""; }
  else { nodes = viewHome(); crumb = "<b>Dashboard</b>"; }
  view.append(...nodes);
  $("#crumb").innerHTML = crumb;
  renderSidebar();
  requestAnimationFrame(() => { liveEditors.forEach(cm => cm.refresh()); applyHighlight(); });
  if (route !== "home" && Engine.status === "idle" && !Engine.starting) setTimeout(() => Engine.start().catch(() => {}), 800);
}

