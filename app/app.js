function itemFor(id) {
  // ids: c-01-3 (card) or q-01-2 (quiz)
  const [kind, mid, idx] = id.split("-");
  const m = byId[mid]; if (!m || !m.learn) return null;
  if (kind === "c") { const c = m.learn.cards[+idx]; return c && { id, kind: "card", mid, front: c[0], back: c[1] }; }
  const q = m.learn.quiz[+idx]; return q && { id, kind: "quiz", mid, q };
}
function addToDeck(id, box = 0) {
  const s = Store.state.srs;
  if (s[id]) return false;
  s[id] = { box, due: today() + (box ? INTERVALS[box] : 1), last: today(), reps: 0, lapses: 0 };
  return true;
}
function grade(id, g) { // 0 again, 1 hard, 2 good, 3 easy
  const s = Store.state.srs[id] ||= { box: 0, due: today(), last: today(), reps: 0, lapses: 0 };
  if (g === 0) { s.box = 1; s.lapses++; s.due = today() + 1; }
  else if (g === 1) { s.box = Math.max(1, s.box); s.due = today() + Math.max(1, Math.round(INTERVALS[s.box] / 2)); }
  else { s.box = Math.min(INTERVALS.length - 1, s.box + (g === 3 ? 2 : 1)); s.due = today() + INTERVALS[s.box]; }
  s.last = today(); s.reps++;
}
function nextIntervalLabel(id, g) {
  const s = Store.state.srs[id] || { box: 0 };
  let days;
  if (g === 0) days = 1;
  else if (g === 1) days = Math.max(1, Math.round(INTERVALS[Math.max(1, s.box)] / 2));
  else days = INTERVALS[Math.min(INTERVALS.length - 1, s.box + (g === 3 ? 2 : 1))];
  return days === 1 ? "tomorrow" : `${days} days`;
}
