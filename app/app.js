function makeEditor(host, value, opts = {}) {
  const editable = !opts.readOnly;
  const python = (opts.mode || "python") === "python";
  const toggleComment = c => c.toggleComment({ indent: true });
  const cm = CodeMirror(host, {
    value, mode: opts.mode || "python", lineNumbers: opts.lineNumbers ?? true, indentUnit: 4,
    tabSize: 4, viewportMargin: Infinity, readOnly: opts.readOnly || false, lineWrapping: false,
    matchBrackets: true,
    autoCloseBrackets: editable ? { pairs: "()[]{}''\"\"", explode: "()[]{}" } : false,
    styleActiveLine: editable,
    gutters: editable && python ? ["CodeMirror-linenumbers", "CodeMirror-lint-markers"] : ["CodeMirror-linenumbers"],
    lint: editable && python ? { getAnnotations: pyLint, async: true, delay: 500, tooltips: true } : false,
    extraKeys: {
      Tab: c => c.somethingSelected() ? c.indentSelection("add") : c.replaceSelection("    ", "end"),
      "Shift-Tab": c => c.indentSelection("subtract"),
      "Ctrl-Enter": () => opts.onRun && opts.onRun(),
      "Cmd-Enter": () => opts.onRun && opts.onRun(),
      "Ctrl-/": toggleComment, "Cmd-/": toggleComment,
      "Ctrl-Space": c => editable && python && showHints(c),
    },
  });
  if (editable && python) {
    cm.on("inputRead", (c, change) => {
      if (c.state.completionActive || change.origin !== "+input") return;
      const ch = change.text[change.text.length - 1].slice(-1);
      if (ch === ".") return showHints(c);
      if (!/\w/.test(ch)) return;
      const cur = c.getCursor(), line = c.getLine(cur.line);
      let start = cur.ch; while (start > 0 && /\w/.test(line[start - 1])) start--;
      if (cur.ch - start >= 2) showHints(c);
    });
    // re-check syntax once Python finishes loading
    if (Engine.status !== "ready") Engine.start().then(() => cm.performLint && cm.performLint()).catch(() => {});
  }
  liveEditors.push(cm);
  return cm;
}

function isRunnable(code) {
  if (/^\s*>>>/m.test(code) || /Traceback \(most recent/.test(code)) return false;
  if (/requests\.(get|post)\(|pip install|breakpoint\(\)|@app\./.test(code)) return false;
  return true;
}

function codeBlock(code, { key = "play", cwd = "/course/play", support = null, lang = "python", runnable = true } = {}) {
  const wrap = h("div", { class: "codeblock" });
  const isPy = lang === "python";
  const canRun = isPy && runnable && isRunnable(code);
  const top = h("div", { class: "bar-top" }, h("span", { class: "lang" }, isPy ? (canRun ? "python · editable" : "python") : (lang || "text")));
  wrap.append(top);
  if (!isPy) {
    wrap.append(h("pre", { class: "static" }, code));
    return wrap;
  }
  const host = h("div"); wrap.append(host);
  const original = code;
  let ran = false;
  const needsInput = /input\(/.test(code);
  let stdinBox = null;
  const outEl = h("pre", { class: "output", hidden: true });
  const run = async (prediction) => {
    Store.studied();
    outEl.hidden = false; outEl.textContent = Engine.status === "ready" ? "Running…" : "Starting Python (first run takes a few seconds)…";
    try {
      const res = await Engine.run({ code: cm.getValue(), key, cwd, support, stdin: stdinBox ? stdinBox.value.split("\n") : [] });
      renderOutput(outEl, res);
      ran = true;
      if (prediction != null) showCompare(prediction, res);
    } catch (e) {
      outEl.textContent = e.timeout ? "Stopped after 10 seconds. Is there a loop that never ends?" :
        e.stopped ? "Stopped." : "Python couldn't start here: " + e.message + ". Copy the code and run it on your computer instead.";
    }
  };
  const cm = makeEditor(host, code, { onRun: () => trigger(), lineNumbers: code.split("\n").length > 3 });
  const predictPanel = h("div", { class: "predict", hidden: true });
  const compare = h("div", { class: "compare", hidden: true });
  function showCompare(pred, res) {
    const actual = plainOutput(res);
    const match = normalise(pred) === normalise(actual);
    Store.state.predictions.made++; if (match) Store.state.predictions.right++;
    Store.save();
    compare.hidden = false; compare.innerHTML = "";
    compare.append(
      h("div", {}, h("strong", {}, "Your prediction"), h("pre", {}, pred || "(blank)")),
      h("div", {}, h("strong", { style: `color:var(${match ? "--good" : "--bad"})` }, match ? "Match. Nice." : "Different. Spot why before moving on."), h("pre", {}, actual || "(nothing printed)")),
    );
  }
  const trigger = () => {
    if (Store.state.predict && !ran && !predictPanel.dataset.skip) {
      predictPanel.hidden = false;
      $("textarea", predictPanel).focus();
      return;
    }
    run(null);
  };
  predictPanel.append(
    h("label", { for: "p" + Math.random().toString(36).slice(2) }, "Predict first: what will this print?"),
    h("textarea", { placeholder: "Type the output you expect. Guessing wrong is how this sticks." }),
    h("div", { class: "row" },
      h("button", { class: "btn small amber", type: "button", onclick: () => { predictPanel.hidden = true; run($("textarea", predictPanel).value); } }, "Run and compare"),
      h("button", { class: "btn small ghost", type: "button", onclick: () => { predictPanel.dataset.skip = "1"; predictPanel.hidden = true; run(null); } }, "Just run it")),
  );
  if (canRun) {
    top.append(
      h("button", { class: "btn small primary", type: "button", onclick: trigger, title: "Ctrl+Enter" }, "▶ Run"),
      h("button", { class: "btn small ghost", type: "button", onclick: () => { cm.setValue(original); outEl.hidden = true; compare.hidden = true; } }, "Reset"),
    );
    if (needsInput) {
      stdinBox = h("textarea", { placeholder: "One line per input() call" });
      wrap.append(h("div", { class: "stdin" }, "Input (what you'd type when the program asks):", stdinBox));
    }
    wrap.append(predictPanel, outEl, compare);
  }
  return wrap;
}

function renderMd(md, ctx = {}) {
  const div = h("div", { class: "prose", html: marked.parse(md) });
  $$("table", div).forEach(t => { const w = h("div", { class: "table-wrap" }); t.replaceWith(w); w.append(t); });
  $$("a[href^='http']", div).forEach(a => { a.target = "_blank"; a.rel = "noopener"; });
  $$("pre > code", div).forEach(code => {
    const pre = code.parentElement;
    const m = /language-(\w+)/.exec(code.className || "");
    const lang = m ? m[1] : "";
    const text = code.textContent.replace(/\n$/, "");
    pre.replaceWith(codeBlock(text, { ...ctx, lang: lang === "py" ? "python" : lang }));
  });
  return div;
}

/* =====================================================================
   Quiz questions (retrieval practice + confidence + elaborative feedback)
   ===================================================================== */
function renderQuestion(q, { mode = "quiz", prior = null, onDone = () => {}, key = "quiz" } = {}) {
  const box = h("div", { class: "q" });
  const isOutput = q.type === "output";
  box.append(h("p", { class: "q-text", html: inlineMd(q.q) }));
  if (q.code) box.append(h("pre", { class: "q-code" }, q.code));
  const askConfidence = mode !== "pretest";
  let picked = null;

  const finish = (correct, confidence, given) => {
    const fb = h("div", { class: "feedback " + (correct ? "ok" : "no") });
    if (mode === "pretest") {
      fb.className = "feedback " + (correct ? "ok" : "no");
      fb.append(h("strong", {}, correct ? "Right, good instinct." : "Not quite, and that's useful."),
        h("div", {}, correct ? "The lesson will explain exactly why." :
          "Guessing before you learn primes your memory. Watch for the answer in the lesson."));
    } else {
      fb.append(h("strong", {}, correct ? "Correct" : "Not this time"));
      if (isOutput && !correct) fb.append(h("div", {}, "Python prints:"), h("pre", { class: "q-code" }, q.answer));
      if (!isOutput && !correct) fb.append(h("div", { html: "Answer: " + inlineMd(q.options[q.answer]) }));
      fb.append(h("div", { html: inlineMd(q.why) }));
      if (prior) fb.append(h("div", { class: "muted", html: `Before the lesson you said: <em>${esc(prior.given || "(no answer)")}</em> ${prior.correct ? "(right)" : "(wrong)"}` }));
      if (confidence === "sure" && !correct) fb.append(h("div", {}, "You felt sure, so this is a classic illusion of knowing. It's now scheduled for review soon."));
    }
    if (isOutput && mode !== "pretest") {
      const out = h("pre", { class: "output", hidden: true });
      fb.append(h("div", { class: "row" }, h("button", {
        class: "btn small", type: "button", onclick: async () => {
          out.hidden = false; out.textContent = "Running…";
          try { renderOutput(out, await Engine.run({ code: q.code, key: "q-" + Math.random(), cwd: "/course/quiz", fresh: true })); }
          catch (e) { out.textContent = "Python isn't available here right now."; }
        },
      }, "▶ Run it yourself")), out);
    }
    box.append(fb);
    if (askConfidence && confidence) {
      Store.state.calib.push({ c: confidence, ok: correct });
      Store.state.calib = Store.state.calib.slice(-400);
    }
    Store.studied(); Store.save();
    onDone({ correct, confidence, given });
  };

  const confidenceStep = (cb) => {
    if (!askConfidence) return cb(null);
    const c = h("div", { class: "confidence" },
      h("div", { class: "eyebrow" }, "How sure are you?"),
      h("div", { class: "row" }, ...[["sure", "Sure"], ["unsure", "Fairly sure"], ["guess", "Guessing"]].map(([k, label]) =>
        h("button", { class: "btn small", type: "button", onclick: () => { c.remove(); cb(k); } }, label))));
    box.append(c);
    $("button", c).focus();
  };

  if (isOutput) {
    const ta = h("textarea", { class: "answer-input", placeholder: "Type exactly what you think Python prints" });
    const btn = h("button", { class: "btn primary", type: "button" }, "Check");
    btn.onclick = () => {
      const given = ta.value;
      ta.disabled = true; btn.remove();
      confidenceStep(conf => finish(normalise(given) === normalise(q.answer), conf, given));
    };
    ta.addEventListener("keydown", e => { if (e.key === "Enter" && (e.ctrlKey || e.metaKey)) btn.click(); });
    box.append(ta, h("div", { class: "row" }, btn, h("span", { class: "muted" }, "Ctrl+Enter")));
  } else {
    const order = shuffle(q.options.map((_, i) => i));
    const opts = h("div", { class: "options", role: "group" });
    order.forEach((oi, n) => {
      const b = h("button", { class: "opt", type: "button" }, h("span", { class: "key" }, String(n + 1)), h("span", { html: inlineMd(q.options[oi]) }));
      b.onclick = () => {
        if (picked !== null) return;
        picked = oi;
        $$(".opt", opts).forEach(x => (x.disabled = true));
        b.classList.add("picked");
        confidenceStep(conf => {
          const correct = oi === q.answer;
          $$(".opt", opts).forEach((x, k) => {
            if (order[k] === q.answer) x.classList.add("right");
            else if (order[k] === oi) x.classList.add("wrong");
          });
          finish(correct, conf, q.options[oi].replace(/`/g, ""));
        });
      };
      opts.append(b);
    });
    box.append(opts);
    box.tabIndex = -1;
    box.addEventListener("keydown", e => {
      const n = parseInt(e.key, 10);
      if (n >= 1 && n <= order.length && !e.target.matches("textarea,input")) $$(".opt", opts)[n - 1].click();
    });
  }
  return box;
}

