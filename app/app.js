function viewPractice(m, body, onNext) {
  const p = Store.mod(m.id);
  const saved = p.code;
  body.append(h("div", { class: "spread" }, h("h2", {}, "Practice"), h("span", { class: "muted" }, p.exTotal ? `${p.exPassed}/${p.exTotal} passing` : "")),
    h("p", { class: "muted" }, "Fill in each function where it says TODO, then press Run checks. Work on one at a time; each ✗ tells you what went wrong. Click a check to jump to its code."));
  const host = h("div", { class: "codeblock editor-tall" }, h("div", { class: "bar-top" }, h("span", { class: "lang" }, `exercises.py · module ${m.id}`)));
  const edHost = h("div"); host.append(edHost);
  host.append(editorHelp());
  const results = h("div", { class: "results" });
  const printed = h("pre", { class: "output", hidden: true });
  let cm;
  const runChecks = async () => {
    p.code = cm.getValue(); Store.studied(); Store.save();
    results.innerHTML = ""; results.append(h("div", { class: "muted" }, Engine.status === "ready" ? "Checking…" : "Starting Python (the first run takes a few seconds)…"));
    try {
      const res = await Engine.check({ mid: m.id, code: cm.getValue(), tests: m.exercise.tests, support: m.support || {} });
      results.innerHTML = "";
      printed.hidden = !res.out; printed.textContent = res.out ? "Your prints:\n" + res.out : "";
      if (res.load_error) {
        results.append(h("div", { class: "callout bad" }, h("strong", {}, "Your file couldn't load. "), "Usually a typo. Read the last line first:",
          h("pre", { class: "output", style: "border:0;background:transparent;padding:8px 0 0" }, res.load_error),
          ERROR_HINTS[res.etype] ? h("div", {}, ERROR_HINTS[res.etype]) : null));
        p.exRuns++; Store.save(); return;
      }
      const passed = res.results.filter(r => r.status === "pass").length;
      const prev = p.exPassed;
      p.exPassed = passed; p.exTotal = res.results.length; p.exRuns++;
      Store.save(); renderSidebar();
      const head = h("div", { class: "spread" }, h("strong", {}, `${passed}/${res.results.length} checks passing`), passed > prev ? h("span", { style: "color:var(--good)" }, `+${passed - prev} since last run`) : null);
      results.append(head, h("div", { class: "progress" }, h("i", { style: `width:${passed / res.results.length * 100}%;background:var(--good)` })));
      res.results.forEach(r => {
        const icon = { pass: "✓", fail: "✗", todo: "…" }[r.status];
        results.append(h("button", { class: "res " + r.status, type: "button", onclick: () => jumpTo(r.name.slice(5)) },
          h("span", { class: "ic" }, icon), h("span", {}, r.label + (r.status === "todo" ? " · not started" : ""), r.msg ? h("span", { class: "msg" }, r.msg) : null)));
      });
      if (passed === res.results.length) {
        results.append(h("div", { class: "callout good" }, h("strong", {}, "Everything passes. "), "Next: the recall quiz.",
          h("div", { class: "row", style: "margin-top:10px" }, h("button", { class: "btn primary", type: "button", onclick: onNext }, "Take the quiz →"))));
      }
    } catch (e) {
      results.innerHTML = "";
      results.append(h("div", { class: "callout bad" }, e.timeout ? "Stopped after 20 seconds. Look for a while loop whose condition never becomes False." :
        "Python couldn't start in this view. You can still use the terminal version: download the course and run python check.py " + Number(m.id) + "."));
    }
  };
  cm = makeEditor(edHost, saved || m.exercise.code, { onRun: runChecks });
  let t; cm.on("change", () => { clearTimeout(t); t = setTimeout(() => { p.code = cm.getValue(); Store.save(); }, 600); });
  function jumpTo(name) {
    const words = name.split("_");
    const camel = words.map(w => w[0].toUpperCase() + w.slice(1)).join("");
    const lines = cm.getValue().split("\n");
    const tries = [new RegExp(`^def ${name}\\b`), new RegExp(`^class ${camel}\\b`), new RegExp(`^(def|class) ${words[0]}`, "i"), new RegExp(`class ${words[0]}`, "i")];
    for (const re of tries) {
      const ln = lines.findIndex(l => re.test(l));
      if (ln >= 0) { cm.focus(); cm.setCursor({ line: ln + 1, ch: 4 }); cm.scrollIntoView({ line: ln, ch: 0 }, 120); host.scrollIntoView({ behavior: "smooth", block: "start" }); return; }
    }
  }
  const solWrap = h("div", { hidden: true, style: "margin-top:16px" });
  const solBtn = h("button", { class: "btn ghost", type: "button", onclick: () => {
    if (p.exRuns < 2 && !solBtn.dataset.confirm) {
      solBtn.dataset.confirm = "1";
      solBtn.textContent = "Run checks at least twice first, or click again to show anyway";
      return;
    }
    solWrap.hidden = !solWrap.hidden;
    solBtn.textContent = solWrap.hidden ? "Show solution" : "Hide solution";
    if (!solWrap.childElementCount) {
      const wrap = h("div", { class: "codeblock solution-wrap" }, h("div", { class: "bar-top" }, h("span", { class: "lang" }, "solutions.py · read it, close it, then write your own version")));
      const e = h("div"); wrap.append(e); solWrap.append(wrap);
      makeEditor(e, m.exercise.solution, { readOnly: true });
    }
    liveEditors.forEach(c => c.refresh());
  } }, "Show solution");
  body.append(host,
    h("div", { class: "row", style: "margin-top:12px" },
      h("button", { class: "btn primary", type: "button", onclick: runChecks, title: "Ctrl+Enter" }, "▶ Run checks"),
      h("button", { class: "btn", type: "button", onclick: () => Engine.stop() }, "Stop"),
      h("button", { class: "btn ghost", type: "button", onclick: function () {
        if (this.dataset.confirm !== "1") { this.dataset.confirm = "1"; this.textContent = "Click again to erase your code"; return; }
        cm.setValue(m.exercise.code); this.dataset.confirm = ""; this.textContent = "Reset to starter";
      } }, "Reset to starter"),
      solBtn),
    h("div", { style: "margin-top:16px" }, results), printed, solWrap);
  if (pendingFind) { const f = pendingFind; pendingFind = null; setTimeout(() => jumpTo(f), 80); }
}

